// Turns docs/devpost/story.md (and the tagline and built-with tags in checklist.md) into a static page laid
// out roughly the way Devpost shows a project: a title, the tagline, the gallery, the story in a column about
// 750 px wide, then the built-with tags. It understands only the Markdown the story uses: images on their own
// line, ## and ### headings, paragraphs, "- " lists, tables, **bold**, `code` and [links](url).
// Picture addresses on the live site are made relative, so the preview works before the pictures are live.

const LIVE = "https://jester-pi.vercel.app/devpost/";

const escape = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const local = (url) => (url.startsWith(LIVE) ? url.slice(LIVE.length) : url);

function inline(text) {
  return escape(text)
    .replace(/!\[([^\]]*)\]\(([^)]+)\)/g, (_, alt, url) => `<img src="${local(url)}" alt="${alt}">`)
    .replace(/\[([^\]]+)\]\((https?:[^)]+)\)/g, '<a href="$2">$1</a>')
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/(^|[\s(])(https?:\/\/[^\s<)]+)/g, '$1<a href="$2">$2</a>')
    .replace(/\[check([^\]]*)\]/g, '<mark title="Aaron: confirm or remove before pasting">[check$1]</mark>');
}

function markdown(md) {
  const lines = md.replace(/\r/g, "").split("\n");
  const out = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }
    const img = line.match(/^!\[([^\]]*)\]\(([^)]+)\)\s*$/);
    if (img) { out.push(`<p class="pic"><img src="${local(img[2])}" alt="${escape(img[1])}"></p>`); i++; continue; }
    const head = line.match(/^(#{2,3}) (.*)$/);
    if (head) { out.push(`<h${head[1].length}>${inline(head[2])}</h${head[1].length}>`); i++; continue; }
    if (line.startsWith("- ")) {
      const items = [];
      while (i < lines.length && lines[i].startsWith("- ")) items.push(`<li>${inline(lines[i++].slice(2))}</li>`);
      out.push(`<ul>${items.join("")}</ul>`);
      continue;
    }
    if (line.startsWith("|")) {
      const rows = [];
      while (i < lines.length && lines[i].startsWith("|")) rows.push(lines[i++]);
      const cells = (row) => row.split("|").slice(1, -1).map((c) => c.trim());
      const [headRow, , ...body] = rows;
      out.push(`<table><thead><tr>${cells(headRow).map((c) => `<th>${inline(c)}</th>`).join("")}</tr></thead><tbody>${
        body.map((r) => `<tr>${cells(r).map((c) => `<td>${inline(c)}</td>`).join("")}</tr>`).join("")}</tbody></table>`);
      continue;
    }
    const para = [];
    while (i < lines.length && lines[i].trim() && !/^(!\[|#{2,3} |- |\|)/.test(lines[i])) para.push(lines[i++]);
    out.push(`<p>${inline(para.join(" "))}</p>`);
  }
  return out.join("\n");
}

/** The first ```text block under a "## <title>" heading in the checklist. */
function block(checklist, title) {
  const at = checklist.indexOf(`## ${title}`);
  if (at < 0) return "";
  const m = checklist.slice(at).match(/```text\n([\s\S]*?)```/);
  return m ? m[1].trim() : "";
}

